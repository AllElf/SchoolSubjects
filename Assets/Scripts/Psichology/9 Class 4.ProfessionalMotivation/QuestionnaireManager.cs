    // Метод OnValidate вызывается в редакторе Unity при изменении объекта
    void OnValidate()
    {
        if (!isInitialized) // Проверяем, было ли уже выполнено автозаполнение
        {
            AutoFillQuestions(); // Выполняем автозаполнение вопросов и ответов
            isInitialized = true; // Устанавливаем флаг, чтобы больше не вызывать автозаполнение
        }
    }

    // Метод для автоматического заполнения списка вопросов
    void AutoFillQuestions()
    {
        questions.Clear(); // Очищаем список вопросов перед заполнением
        for (int i = 0; i < questionTexts.Length; i++) // Проходим по каждому тексту вопроса
        {
            var question = new QuestionData // Создаём новый объект вопроса
            {
                question = questionTexts[i], // Устанавливаем текст вопроса
                options = new AnswerOption[3] // Инициализируем массив из трёх ответов
            };

            for (int j = 0; j < 3; j++) // Заполняем три варианта ответа для текущего вопроса
            {
                question.options[j] = new AnswerOption
                {
                    text = answerOptions[i, j], // Устанавливаем текст ответа из массива
                    groupIndex = j % 4, // Циклический индекс группы (от 0 до 3)
                    score = 1 // Устанавливаем баллы по умолчанию
                };
            }

            questions.Add(question); // Добавляем вопрос в список
        }
    }

    // Метод Start вызывается при запуске игры
    void Start()
    {
        if(buttonPush != null)
        {
            buttonPush.SetActive(false);
        }
        
        nextButton.onClick.AddListener(NextQuestion); // Добавляем обработчик нажатия на кнопку "Далее"
        LoadQuestion(); // Загружаем первый вопрос
    }

    // Метод для загрузки текущего вопроса
    void LoadQuestion()
    {
        if (currentQuestion < questions.Count) // Проверяем, есть ли ещё вопросы
        {
            var questionData = questions[currentQuestion]; // Получаем текущий вопрос
            questionText.text = questionData.question; // Устанавливаем текст вопроса
            option1.GetComponentInChildren<Text>().text = questionData.options[0].text; // Устанавливаем текст первого ответа
            option2.GetComponentInChildren<Text>().text = questionData.options[1].text; // Устанавливаем текст второго ответа
            option3.GetComponentInChildren<Text>().text = questionData.options[2].text; // Устанавливаем текст третьего ответа
        }
        else
        {
            CalculateResults(); // Если вопросы закончились, вычисляем результаты
            nextButton.interactable = false; // Отключаем кнопку
            if (buttonPush != null)
            {
                buttonPush.SetActive(true);
            }
        }
    }

    // Метод для перехода к следующему вопросу
    void NextQuestion()
    {
        if (optionsGroup.AnyTogglesOn()) // Проверяем, выбран ли хотя бы один ответ
        {
            int selectedIndex = GetSelectedOption(); // Получаем индекс выбранного ответа
            if (selectedIndex != -1)
            {
                var selectedOption = questions[currentQuestion].options[selectedIndex]; // Получаем выбранный вариант ответа
                groupScores[selectedOption.groupIndex] += selectedOption.score; // Увеличиваем баллы соответствующей группы
            }

            currentQuestion++; // Переходим к следующему вопросу
            LoadQuestion(); // Загружаем следующий вопрос
        }
        else
        {
            Debug.Log("Пожалуйста, выберите ответ."); // Выводим сообщение, если не выбран ни один ответ
        }
    }

    // Метод для получения индекса выбранного ответа
    int GetSelectedOption()
    {
        if (option1.isOn) return 0; // Если выбран первый переключатель, возвращаем 0
        if (option2.isOn) return 1; // Если выбран второй переключатель, возвращаем 1
        if (option3.isOn) return 2; // Если выбран третий переключатель, возвращаем 2
        return -1; // Если ни один переключатель не выбран, возвращаем -1
    }

    // Метод для расчёта результатов
    void CalculateResults()
    {
        string result = "Результаты:\n"; // Инициализируем строку для результатов

        for (int i = 0; i < groupScores.Length; i++) // Проходим по каждой группе
        {
            result += $"{i + 1}-я группа ({groupDescriptions[i]}): {groupScores[i]}\n"; // Добавляем баллы группы к результату
        }

        motivationAnalysis = AnalyzeMotivation(); // Выполняем анализ мотивации
        string motivationResult = $"\nАнализ мотивации: {motivationAnalysis}"; // Добавляем анализ к результатам
        result += $"\nАнализ мотивации: {motivationAnalysis}"; // Добавляем анализ к результатам
        countingInformationPsychology._answer = motivationResult;
        resultText.text = motivationResult; // Устанавливаем текст результатов в UI
    }

    // Метод для анализа мотивации
    string AnalyzeMotivation()
    {
        int maxScore = Mathf.Max(groupScores); // Находим максимальный балл среди всех групп
        List<string> dominantGroups = new List<string>(); // Список для хранения преобладающих групп

        for (int i = 0; i < groupScores.Length; i++) // Проходим по каждой группе
        {
            if (groupScores[i] == maxScore) // Если группа имеет максимальный балл
            {
                countingInformationPsychology._scores = groupScores[i];
                dominantGroups.Add(groupDescriptions[i]); // Добавляем её в список преобладающих
            }
        }

        // Возвращаем анализ мотивации
        return dominantGroups.Count == 1
            ? $"Преобладающая мотивация: {dominantGroups[0]}" // Если одна группа, возвращаем её
            : $"Смешанный тип мотивации: {string.Join(", ", dominantGroups)}"; // Если несколько, возвращаем все
    }
}

[System.Serializable]
public class QuestionData
{
    public string question; // Текст вопроса
    public AnswerOption[] options; // Массив вариантов ответа
}

[System.Serializable]
public class AnswerOption
{
    public string text; // Текст ответа
    public int groupIndex; // Индекс группы мотивации
    [Range(1, 10)] public int score = 1; // Баллы за ответ с диапазоном от 1 до 10
}